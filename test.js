const fs=require('fs'),path=require('path'),assert=require('node:assert/strict');
const lib=require('./checker.js');
const dir=__dirname;
const csv=fs.readFileSync(path.join(dir,'synthetic_survey.csv'),'utf8');
const expected=JSON.parse(fs.readFileSync(path.join(dir,'expected_results.json'),'utf8'));
const data=lib.parseCSV(csv);
const res=lib.check(data,{ranges:{price_sensitivity_1to5:[1,5],brand_trust_1to5:[1,5],purchase_intent_1to5:[1,5],age:[18,100]},idColumn:'respondent_id'});
assert.equal(res.rows,expected.rows);assert.equal(res.columns,expected.columns);
assert.deepEqual(res.missing,expected.missing_by_column);
for(const [k,v] of Object.entries(expected.invalid_scale_by_column))assert.equal(res.invalidRanges[k],v);
assert.equal(res.invalidRanges.age,expected.invalid_age);
assert.equal(res.exactDuplicateRows,expected.exact_duplicate_rows);
assert.equal(res.duplicateIds,expected.duplicate_respondent_ids);
assert.equal(lib.parseCSV('a,b\r\n"hello, world","say ""yes"""\r\n').rows[0][1],'say "yes"');
for(const invalid of ['a,b\n1\n','a,b\n"x"oops,2','a,b\nfoo"bar,2','a,b\n"unclosed,2'])assert.throws(()=>lib.parseCSV(invalid));
assert.throws(()=>lib.check(data,{ranges:{age:[100,18]}}));
const sample=lib.parseCSV('id,satisfied\n1,Yes\n2,No\n3,Yes\n4,\n');
const claim=lib.checkClaim(sample,{column:'satisfied',option:'Yes',claimedPercent:66.7,recruitment:'voluntary'});
assert.equal(claim.numerator,2);assert.equal(claim.denominator,3);assert.equal(claim.missing,1);assert.equal(claim.withinHalfPercentagePoint,true);
assert.equal(lib.checkClaim(sample,{column:'satisfied',option:'Yes',claimedPercent:85}).withinHalfPercentagePoint,false);
assert.throws(()=>lib.checkClaim(sample,{column:'satisfied',option:'Yes',claimedPercent:101}));
console.log('PASS: baseline, parser edge cases, range validation, claim checks');
